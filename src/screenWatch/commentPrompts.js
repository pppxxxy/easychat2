// 看屏幕评论 prompt：纯函数、中文（提示词不翻译）。截图本体以多模态 image
// 随请求发送（buildRequestMessages 的 images 参数），这里只交代情境与要求。
// 隐私约束进 prompt：只描述看到的界面，不鼓励猜测屏幕外的信息。

export function buildScreenWatchPrompt() {
  return [
    '用户发来一张当前手机屏幕的截图（就是本应用的界面），想让你「看一眼屏幕」陪他聊聊。',
    '请用两三句口语化的中文说说你看到的内容与感受：界面上有什么、看起来用户正在做什么、或者抛一个想聊的点。',
    '不要复述无法从截图确认的信息，不要编造截图里没有的内容，不要使用任何格式标记，直接输出要说的话。',
  ].join('');
}
